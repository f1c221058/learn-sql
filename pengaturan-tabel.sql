-- Contoh penggunaan kolom IDENTITAS (auto-numbering) versi 1
CREATE TABLE ranks (
  rank_id INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,  -- Kolom auto-increment; nilai selalu di‐generate DB
  rank_name CHAR NOT NULL                                 -- Nama pangkat; tipe CHAR (panjang tetap)
);

