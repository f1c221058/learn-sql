-- Versi 2 IDENTITAS: boleh set manual jika perlu
CREATE TABLE ranks (
  rank_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- DB mengisi default, tapi boleh override manual
  rank_name CHAR NOT NULL
);

INSERT INTO ranks (rank_name) VALUES ('A');               -- rank_id diisi otomatis

INSERT INTO ranks (rank_id, rank_name) VALUES (2, 'B');   -- Diperbolehkan (override nilai identity)

SELECT
  rank_id,
  rank_name
FROM
  ranks;

