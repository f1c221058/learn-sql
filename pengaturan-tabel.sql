-- Membuat tabel 'courses' untuk menyimpan data kursus
CREATE TABLE courses (                           -- Nama tabel: courses
  name VARCHAR(255) NOT NULL,                    -- Kolom nama kursus, wajib diisi
  description TEXT,                              -- Kolom deskripsi, boleh null
  duration DEC(4, 2) NOT NULL                    -- Lama durasi (mis. 12.50), 4 digit total, 2 desimal, wajib
);

